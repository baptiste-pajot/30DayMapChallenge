// Download the OSM points once and save them as data/<category>.js, so the page loads instantly.
// Usage (from anywhere):  node 04_clusters/fetch_data.js [bars schools churches]
// Data files are classic scripts (POIS.<category> = [[lng, lat, name], …]) rather than JSON, because the page
// must work from file://, where fetch() of a local file is blocked but a <script src> is not.
const fs = require('fs');
const path = require('path');

// overpass.js is a classic browser script: evaluate it and pick out what we need.
const { CATEGORIES, fetchOverpass } = new Function(
  fs.readFileSync(path.join(__dirname, 'overpass.js'), 'utf8') + '\nreturn { CATEGORIES, fetchOverpass };')();

(async () => {
  const keys = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(CATEGORIES);
  fs.mkdirSync(path.join(__dirname, 'data'), { recursive: true });
  for (const key of keys) {
    if (!CATEGORIES[key]) { console.error(`Unknown category "${key}"`); process.exitCode = 1; continue; }
    const t0 = Date.now();
    const rows = await fetchOverpass(CATEGORIES[key].filter, {
      onAttempt: host => console.log(`${key}: querying ${host}…`),
      onError: err => console.log(`  failed: ${err.message}`),
      // overpass-api.de refuses Node's default User-Agent (406); browsers send their own.
      headers: { 'User-Agent': '30DayMapChallenge-day04/1.0 (one-off data download)' },
    });
    const file = path.join(__dirname, 'data', `${key}.js`);
    const date = new Date().toISOString().slice(0, 10);
    fs.writeFileSync(file, `// OSM ${key} in mainland France, ${date}. © OpenStreetMap contributors, ODbL. ` +
      `Generated by fetch_data.js.\n(window.POIS = window.POIS || {}).${key} = { date: '${date}', rows: ` +
      JSON.stringify(rows) + ' };\n');
    console.log(`${key}: ${rows.length} points → ${path.relative(process.cwd(), file)} ` +
      `(${(fs.statSync(file).size / 1e6).toFixed(1)} MB, ${((Date.now() - t0) / 1000).toFixed(0)} s)`);
  }
})().catch(err => { console.error(err.message); process.exit(1); });
